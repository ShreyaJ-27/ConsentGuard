/**
 * manifest.ts — Evidence manifest builder.
 *
 * Generates a JSON manifest that the user can review before export.
 * All user-provided fields are labelled as such; the tool never fabricates
 * timestamps, device details, or evidence.
 */

export const MANIFEST_SCHEMA_VERSION = '1.0.0';

export interface EvidenceItem {
  /** Sequential index within the session */
  index: number;
  /** Where the content was found (user-provided) */
  url: string;
  /** Platform or service name (user-provided) */
  platform: string;
  /** ISO 8601 date/time with timezone as entered by user (user-provided) */
  observed_at: string;
  /** Free-text notes (user-provided) */
  notes: string;
  /** SHA-256 hex of a selected file, computed locally (tool-computed) */
  sha256?: string;
  /** dHash hex of a selected image, computed locally (tool-computed, PLACEHOLDER format) */
  dhash?: string;
  /** Filename reported by the browser File API (tool-computed from browser metadata) */
  filename?: string;
}

export interface ManifestData {
  schema_version: string;
  tool: string;
  tool_version: string;
  /** ISO 8601 timestamp of manifest creation (tool-computed from browser clock) */
  created_at: string;
  disclaimer: string;
  data_sources: string;
  evidence_items: EvidenceItem[];
  /** SHA-256 of the selected file if computed */
  file_sha256?: string;
  /** dHash of the selected image if computed */
  file_dhash?: string;
  /** Filename reported by the browser (browser metadata) */
  selected_filename?: string;
  /** Fields explicitly included in this manifest */
  included_fields: string[];
}

export function buildManifest(params: {
  evidenceItems: EvidenceItem[];
  fileSha256?: string;
  fileDHash?: string;
  selectedFilename?: string;
  appVersion?: string;
}): ManifestData {
  const { evidenceItems, fileSha256, fileDHash, selectedFilename, appVersion } = params;

  const includedFields: string[] = ['schema_version', 'tool', 'created_at', 'evidence_items'];
  if (fileSha256) includedFields.push('file_sha256');
  if (fileDHash) includedFields.push('file_dhash');
  if (selectedFilename) includedFields.push('selected_filename');

  return {
    schema_version: MANIFEST_SCHEMA_VERSION,
    tool: 'ConsentGuard Rescue Kit',
    tool_version: appVersion ?? 'unknown',
    created_at: new Date().toISOString(),
    disclaimer:
      'This evidence pack is a collection aid only. It is not legally admissible ' +
      'on its own and has not been reviewed by a lawyer. Do not share this file ' +
      'without consulting a legal professional.',
    data_sources:
      'Fields labelled (user-provided) were entered by the user and have not been ' +
      'independently verified. Fields labelled (tool-computed) were generated by ' +
      'the browser-side tool from data on the device.',
    evidence_items: evidenceItems,
    file_sha256: fileSha256,
    file_dhash: fileDHash,
    selected_filename: selectedFilename,
    included_fields: includedFields,
  };
}

export function manifestToJsonString(manifest: ManifestData): string {
  return JSON.stringify(manifest, null, 2);
}
